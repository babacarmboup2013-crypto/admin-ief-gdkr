-- Transmissions internes de courriers et de dossiers entre bureaux.
-- Chaque transmission est tracée : émetteur, bureau source, bureau destinataire,
-- note, date et statut d'accusé de réception. L'objet transmis n'est pas déplacé,
-- il reste visible depuis le bureau d'origine et depuis le bureau destinataire.

CREATE TABLE IF NOT EXISTS public.transmissions (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_objet             text NOT NULL CHECK (type_objet IN ('courrier', 'dossier')),
  objet_id               bigint NOT NULL,
  objet_ref              text,
  objet_titre            text,
  bureau_source_id       integer REFERENCES public.bureaux(id),
  bureau_destinataire_id integer NOT NULL REFERENCES public.bureaux(id),
  expediteur_id          uuid REFERENCES public.utilisateurs(id),
  note                   text,
  statut                 text NOT NULL DEFAULT 'en_attente'
                         CHECK (statut IN ('en_attente', 'accepte', 'traite', 'refuse')),
  date_transmission      timestamptz NOT NULL DEFAULT now(),
  date_reponse           timestamptz,
  traite_par             uuid REFERENCES public.utilisateurs(id),
  created_at             timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS transmissions_dest_idx
  ON public.transmissions (bureau_destinataire_id, statut);
CREATE INDEX IF NOT EXISTS transmissions_source_idx
  ON public.transmissions (bureau_source_id, statut);
CREATE INDEX IF NOT EXISTS transmissions_objet_idx
  ON public.transmissions (type_objet, objet_id);

ALTER TABLE public.transmissions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "transmissions_read" ON public.transmissions
  FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "transmissions_insert" ON public.transmissions
  FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "transmissions_update" ON public.transmissions
  FOR UPDATE USING (auth.role() = 'authenticated');
