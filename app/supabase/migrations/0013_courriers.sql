-- ============================================================
-- IEF ADMIN — Archivage électronique des courriers ordinaires
-- Calqué sur le formulaire KoboToolbox :
--   "Système Archivage Electronique des Courriers Ordinaires
--    de l'IEF Grand Dakar"
-- ============================================================

-- ---------- 1. TABLE ----------
create table if not exists public.courriers (
  id                   bigint generated by default as identity primary key,
  -- Certaines soumissions historiques KoboToolbox n'ont pas ces champs :
  -- ils restent donc nullables en base (le formulaire, lui, les exige).
  date_courrier        date,
  numero_reference     text,
  objet                text,
  type_courrier        text not null default 'ordinaire',
  -- Nature (champ conditionnel du formulaire KoboToolbox)
  --   'arriv__ordinaire' -> Arrivé Ordinaire (expéditeur renseigné)
  --   'd_part_ordinaire' -> Départ Ordinaire (destinataire renseigné)
  nature_ordinaire     text,
  expediteur           text,
  destinataire         text,
  transmission_interne text[] not null default '{}',
  fichier_path         text,
  fichier_nom          text,
  -- Traçabilité vers la soumission KoboToolbox d'origine
  kobo_id              bigint unique,
  kobo_uuid            uuid,
  bureau_id            int references public.bureaux (id),
  saisi_par            uuid references public.utilisateurs (id),
  statut               text not null default 'brouillon',  -- brouillon / soumis / archive
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

create index if not exists courriers_bureau_idx on public.courriers (bureau_id);
create index if not exists courriers_date_idx on public.courriers (date_courrier desc);
create index if not exists courriers_statut_idx on public.courriers (statut);

-- ---------- 2. RLS ----------
alter table public.courriers enable row level security;

drop policy if exists "courriers_select" on public.courriers;
create policy "courriers_select"
  on public.courriers for select
  using (auth.role() = 'authenticated');

drop policy if exists "courriers_insert" on public.courriers;
create policy "courriers_insert"
  on public.courriers for insert
  with check (auth.role() = 'authenticated' and saisi_par = auth.uid());

drop policy if exists "courriers_update" on public.courriers;
create policy "courriers_update"
  on public.courriers for update
  using (
    saisi_par = auth.uid()
    or public.is_super_admin()
    or public.is_chef_admin()
  )
  with check (
    saisi_par = auth.uid()
    or public.is_super_admin()
    or public.is_chef_admin()
  );

drop policy if exists "courriers_delete" on public.courriers;
create policy "courriers_delete"
  on public.courriers for delete
  using (
    saisi_par = auth.uid()
    or public.is_super_admin()
    or public.is_chef_admin()
  );

-- ---------- 3. BUCKET STORAGE (pièces jointes, < 10 Mo) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'courriers',
  'courriers',
  false,
  10485760,
  array[
    'application/pdf',
    'image/jpeg',
    'image/png',
    'image/webp',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
  ]::text[]
)
on conflict (id) do update
  set file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- Lecture : personnels authentifiés
drop policy if exists "courriers_storage_read" on storage.objects;
create policy "courriers_storage_read"
  on storage.objects for select
  using (bucket_id = 'courriers' and auth.role() = 'authenticated');

-- Dépôt : personnels authentifiés
drop policy if exists "courriers_storage_insert" on storage.objects;
create policy "courriers_storage_insert"
  on storage.objects for insert
  with check (bucket_id = 'courriers' and auth.role() = 'authenticated');

-- Retrait : super admin, chef admin, ou auteur du dossier
drop policy if exists "courriers_storage_delete" on storage.objects;
create policy "courriers_storage_delete"
  on storage.objects for delete
  using (
    bucket_id = 'courriers'
    and (
      public.is_super_admin()
      or public.is_chef_admin()
      or (storage.foldername(name))[1] = auth.uid()::text
    )
  );
